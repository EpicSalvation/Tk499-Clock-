/* Set the drawing window */
void LCD_SetWindow(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2)
{
    /* Column address set */
    LCD_WriteCmd(0x2A);
    LCD_WriteData(x1 >> 8);
    LCD_WriteData(x1 & 0xFF);
    LCD_WriteData(x2 >> 8);
    LCD_WriteData(x2 & 0xFF);

    /* Row address set */
    LCD_WriteCmd(0x2B);
    LCD_WriteData(y1 >> 8);
    LCD_WriteData(y1 & 0xFF);
    LCD_WriteData(y2 >> 8);
    LCD_WriteData(y2 & 0xFF);

    /* Memory write */
    LCD_WriteCmd(0x2C);
}

/* Clear the screen with a color */
void LCD_Clear(uint16_t color)
{
    uint32_t total = (uint32_t)LCD_WIDTH * LCD_HEIGHT;
    uint32_t color32;

    /* Convert RGB565 to RGB888 for TK80 24-bit mode */
    uint8_t r = ((color >> 11) & 0x1F) << 3;
    uint8_t g = ((color >> 5) & 0x3F) << 2;
    uint8_t b = (color & 0x1F) << 3;
    color32 = (r << 16) | (g << 8) | b;

    LCD_SetWindow(0, 0, LCD_WIDTH - 1, LCD_HEIGHT - 1);

    /* Use TK80 hardware fill mode */
    TK80->CFGR3 = total;
    TK80->DINR = color32;
    while (TK80->SR & 0x10000);
}

/* Draw a single pixel */
void LCD_DrawPixel(uint16_t x, uint16_t y, uint16_t color)
{
    uint32_t color32;

    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;

    /* Convert RGB565 to RGB888 */
    uint8_t r = ((color >> 11) & 0x1F) << 3;
    uint8_t g = ((color >> 5) & 0x3F) << 2;
    uint8_t b = (color & 0x1F) << 3;
    color32 = (r << 16) | (g << 8) | b;

    LCD_SetWindow(x, y, x, y);
    TK80->DINR = color32;
    while (TK80->SR & 0x10000);
}

/* Fill a rectangle */
void LCD_FillRect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
    uint32_t total;
    uint32_t color32;

    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;
    if (x + w > LCD_WIDTH) w = LCD_WIDTH - x;
    if (y + h > LCD_HEIGHT) h = LCD_HEIGHT - y;

    /* Convert RGB565 to RGB888 */
    uint8_t r = ((color >> 11) & 0x1F) << 3;
    uint8_t g = ((color >> 5) & 0x3F) << 2;
    uint8_t b = (color & 0x1F) << 3;
    color32 = (r << 16) | (g << 8) | b;

    LCD_SetWindow(x, y, x + w - 1, y + h - 1);

    total = (uint32_t)w * h;
    /* Use TK80 hardware fill mode */
    TK80->CFGR3 = total;
    TK80->DINR = color32;
    while (TK80->SR & 0x10000);
}

/* Draw a character at position (x, y) */
uint8_t LCD_DrawChar(uint16_t x, uint16_t y, char c, uint16_t fg, uint16_t bg)
{
    uint8_t i, j;
    uint8_t byte;
    const uint8_t *glyph;
    uint32_t fg32, bg32;

    /* Convert colors to RGB888 */
    fg32 = (((fg >> 11) & 0x1F) << 19) | (((fg >> 5) & 0x3F) << 10) | ((fg & 0x1F) << 3);
    bg32 = (((bg >> 11) & 0x1F) << 19) | (((bg >> 5) & 0x3F) << 10) | ((bg & 0x1F) << 3);

    /* Handle characters outside our font range */
    if (c < 32 || c > 126) {
        c = '?';
    }

    glyph = font8x16[c - 32];

    /* Draw character using block write for speed */
    LCD_SetWindow(x, y, x + 7, y + 15);

    for (j = 0; j < 16; j++) {
        byte = glyph[j];
        for (i = 0; i < 8; i++) {
            if (byte & (0x80 >> i)) {
                TK80->DINR = fg32;
            } else {
                TK80->DINR = bg32;
            }
        }
    }

    return 8;  /* Character width */
}

/* Draw a string at position (x, y) */
void LCD_DrawString(uint16_t x, uint16_t y, const char *str, uint16_t fg, uint16_t bg)
{
    while (*str) {
        x += LCD_DrawChar(x, y, *str, fg, bg);
        str++;
    }
}

/* Draw a large (scaled) character */
uint8_t LCD_DrawCharLarge(uint16_t x, uint16_t y, char c, uint16_t fg, uint16_t bg, uint8_t scale)
{
    uint8_t i, j, si, sj;
    uint8_t byte;
    const uint8_t *glyph;

    if (scale == 0) scale = 1;

    /* Handle characters outside our font range */
    if (c < 32 || c > 126) {
        c = '?';
    }

    glyph = font8x16[c - 32];

    for (j = 0; j < 16; j++) {
        byte = glyph[j];
        for (i = 0; i < 8; i++) {
            uint16_t color = (byte & (0x80 >> i)) ? fg : bg;
            /* Draw scaled pixel block */
            for (sj = 0; sj < scale; sj++) {
                for (si = 0; si < scale; si++) {
                    LCD_DrawPixel(x + i * scale + si, y + j * scale + sj, color);
                }
            }
        }
    }

    return 8 * scale;  /* Scaled character width */
}

/* Draw a string with scaling */
void LCD_DrawStringLarge(uint16_t x, uint16_t y, const char *str, uint16_t fg, uint16_t bg, uint8_t scale)
{
    while (*str) {
        x += LCD_DrawCharLarge(x, y, *str, fg, bg, scale);
        str++;
    }
}

/* Draw a single clock digit using 7-segment style */
uint8_t LCD_DrawClockDigit(uint16_t x, uint16_t y, char c, uint16_t fg, uint16_t bg)
{
    if (c >= '0' && c <= '9') {
        draw_7seg_digit(x, y, c - '0', fg, bg);
        return SEG_DIGIT_WIDTH;
    } else if (c == ':') {
        draw_colon(x, y, fg, bg);
        return SEG_COLON_WIDTH;
    } else {
        /* Unknown character - draw space */
        LCD_FillRect(x, y, SEG_DIGIT_WIDTH, SEG_DIGIT_HEIGHT, bg);
        return SEG_DIGIT_WIDTH;
    }
}

/* Draw a clock time string using 7-segment digits */
void LCD_DrawClockTime(uint16_t x, uint16_t y, const char *str, uint16_t fg, uint16_t bg)
{
    while (*str) {
        x += LCD_DrawClockDigit(x, y, *str, fg, bg);
        x += 4;  /* Small gap between characters */
        str++;
    }
}

/*
 * Backlight Control
 * PD8 controls the MP3302 boost converter enable
 */

void LCD_BacklightInit(void)
{
    /* GPIOD clock should already be enabled */
    RCC->AHB1ENR |= (1 << 3);

    /* Configure PD8 as push-pull output */
    GPIOD->CRH &= ~(0x0F << 0);
    GPIOD->CRH |= (0x02 << 0);

    LCD_BacklightOn();
}

void LCD_BacklightOn(void)
{
    GPIOD->BSRR = (1 << 8);
}

void LCD_BacklightOff(void)
{
    GPIOD->BSRR = (1 << 24);
}

void LCD_Backlight(uint8_t on)
{
    if (on) {
        LCD_BacklightOn();
    } else {
        LCD_BacklightOff();
    }
}

/* PWM brightness control - simplified version */
static volatile uint8_t pwm_brightness = 100;

void LCD_BrightnessInit(void)
{
    LCD_BacklightInit();
    pwm_brightness = 100;
}

void LCD_SetBrightness(uint8_t level)
{
    if (level > 100) level = 100;
    pwm_brightness = level;

    /* Simple on/off for now */
    if (level > 0) {
        LCD_BacklightOn();
    } else {
        LCD_BacklightOff();
    }
}

uint8_t LCD_GetBrightness(void)
{
    return pwm_brightness;
}
